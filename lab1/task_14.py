a1 = input("Введите первую последовательность: ")
b1 = input("Введите вторую последовательность: ")
a = list(map(float, a1.split()))
b = list(map(float, b1.split()))
a = set(a)
b = set(b)
print("числа присутствующие в обоих наборах одновременно:", a & b if a&b else "таких чисел нет")  
print("Числа только в первом наборе:", a - b if a - b else "таких чисел нет")  
print("Числа только во втором наборе:", b - a if b - a else "таких чисел нет")
print("Все кроме пересекающихся", a ^ b if a^b else "таких чисел нет")  
